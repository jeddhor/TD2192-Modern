//! `tdtool gen-manifest`: turn the inventory table into `manifest_data.rs`.
//!
//! Classification rules (which files are required) live here so they are reviewed with code:
//! * Usage comes from the inventory's "Referenced by" column; mission files (`mN.td`, `.td2`,
//!   `.td3`) are mapped to their episode by extension because the game builds their names.
//! * Optional: the uncut dialogue scripts (the game falls back to the edited ones), original
//!   config and save files (the port keeps its own), and everything only the launcher, the
//!   intro or nothing at all references.

use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use anyhow::{Context, Result, bail};

const OPTIONAL: &[&str] = &[
    "dialogue.dat",
    "dialogu2.dat",
    "dialogu3.dat",
    "td.cfg",
    "td.sav",
    "td2.sav",
    "td3.sav",
    "td.stt",
    "td2.stt",
    "td3.stt",
];

struct Row {
    name: String,
    size: u64,
    category: &'static str,
    usage: Vec<&'static str>,
    sha256: String,
}

pub fn run(inventory: &Path, out: &Path) -> Result<()> {
    let text = fs::read_to_string(inventory)
        .with_context(|| format!("reading {}", inventory.display()))?;
    let mut rows = parse(&text)?;
    rows.sort_by(|a, b| a.name.cmp(&b.name));

    let mut s = String::new();
    s.push_str(
        "// @generated by `tdtool gen-manifest` from docs/re/FILE_INVENTORY.md. Do not edit.\n\n",
    );
    s.push_str("static FILES: &[ManifestEntry] = &[\n");
    for r in &rows {
        let used_by = if r.usage.is_empty() {
            "Usage::NONE".to_string()
        } else {
            let mut u = format!("Usage::{}", r.usage[0]);
            for x in &r.usage[1..] {
                u = format!("{u}.union(Usage::{x})");
            }
            u
        };
        let episode_use = r.usage.iter().any(|u| u.starts_with('E'));
        let required = episode_use && !OPTIONAL.contains(&r.name.as_str());
        writeln!(
            s,
            "    ManifestEntry {{ name: {:?}, size: {}, sha256: {:?}, category: Category::{}, used_by: {used_by}, required: {required} }},",
            r.name, r.size, r.sha256, r.category
        )?;
    }
    s.push_str("];\n");
    fs::write(out, s).with_context(|| format!("writing {}", out.display()))?;
    println!("wrote {} entries to {}", rows.len(), out.display());
    Ok(())
}

fn parse(text: &str) -> Result<Vec<Row>> {
    let mut rows = Vec::new();
    for line in text.lines().filter(|l| l.starts_with("| `")) {
        let cells: Vec<&str> = line.trim_matches('|').split(" | ").map(str::trim).collect();
        if cells.len() != 7 {
            bail!("expected 7 columns, found {}: {line}", cells.len());
        }
        let name = cells[0].trim_matches('`').to_ascii_lowercase();
        let size: u64 = cells[1].replace(',', "").parse()?;
        let category = category(cells[2])?;
        let sha256 = cells[6].trim_matches('`').to_string();
        if sha256.len() != 64 {
            bail!("bad sha256 for {name}");
        }
        let mut usage = Vec::new();
        for tag in cells[5].split(',').map(str::trim) {
            match tag {
                "td1" => usage.push("LAUNCHER"),
                "intro" => usage.push("INTRO"),
                "E1" => usage.push("E1"),
                "E2" => usage.push("E2"),
                "E3" => usage.push("E3"),
                _ => {}
            }
        }
        if category == "Mission" {
            usage = vec![mission_episode(&name)?];
        }
        rows.push(Row {
            name,
            size,
            category,
            usage,
            sha256,
        });
    }
    if rows.is_empty() {
        bail!("no inventory rows found");
    }
    Ok(rows)
}

fn mission_episode(name: &str) -> Result<&'static str> {
    Ok(match name.rsplit_once('.').map(|(_, e)| e) {
        Some("td") => "E1",
        Some("td2") => "E2",
        Some("td3") => "E3",
        _ => bail!("unexpected mission file name {name}"),
    })
}

fn category(s: &str) -> Result<&'static str> {
    Ok(match s {
        "exe" => "Exe",
        "doc" => "Doc",
        "palette" => "Palette",
        "screen" => "Screen",
        "picture" => "Picture",
        "portraits" => "Portraits",
        "ui-gfx" => "UiGfx",
        "tileset" => "Tileset",
        "map" => "Map",
        "sprites" => "Sprites",
        "mission" => "Mission",
        "dialogue" => "Dialogue",
        "font" => "Font",
        "config" => "Config",
        "save" => "Save",
        "music" => "Music",
        "sfx" => "Sfx",
        "presentation" => "Presentation",
        other => bail!("unknown category {other:?}"),
    })
}
